CREATE TABLE CUSTOMERS (
    id          Number(19)      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name  VARCHAR2(100)   NOT NULL,
    last_name   VARCHAR2(100)   NOT NULL,
    email       VARCHAR2(255)   NOT NULL,
    created_at  TIMESTAMP(6)    WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT   uk_customers_email UNIQUE (email)
);

CREATE TABLE accounts (
  id             NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_number VARCHAR2(20)  NOT NULL,
  account_type   VARCHAR2(10)  NOT NULL,
  balance        NUMBER(19,2)  DEFAULT 0 NOT NULL,
  status         VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
  customer_id    NUMBER(19)    NOT NULL,
  version        NUMBER(19)    DEFAULT 0 NOT NULL,
  created_at     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uk_accounts_number UNIQUE (account_number),
  CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT ck_accounts_type   CHECK (account_type IN ('CHECKING','SAVINGS')),
  CONSTRAINT ck_accounts_status CHECK (status IN ('ACTIVE','FROZEN','CLOSED')),
  CONSTRAINT ck_accounts_balance CHECK (balance >= 0)
);

CREATE INDEX ix_accounts_customer ON accounts (customer_id);